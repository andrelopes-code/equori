func TestEnvExample(t *testing.T) {
	want := `# equori: variables of compose.yaml, read from .env in this directory.
# Reference: https://github.com/andrelopes-code/equori/blob/main/docs/install/configuration.md
# The installation script writes A_PASS.

# Pass. Expected: letters. Default: x.
A_PASS=

# Address. Expected: an IP address. Default: 127.0.0.1.
# A_IP=127.0.0.1
`

	got := envExample(testVariables())
	if got != want {
		t.Fatalf("envExample:\n%s\nwant:\n%s", got, want)
	}
}

func TestMarkdown(t *testing.T) {
	prefix := "<!-- Generated by make gen from internal/platform/config/variables.go; do not edit. -->\n\n# Configuration\n\n"
	suffix := "## Installation\n\n" +
		"| Variable | Read by | Expected | Default | Example | Description |\n" +
		"|---|---|---|---|---|---|\n" +
		"| `A_PASS` | `compose.yaml` | letters | `x` | `y` | Pass. |\n" +
		"| `A_IP` | `compose.yaml` | an IP address | `127.0.0.1` | `0.0.0.0` | Address. |\n\n" +
		"## Development\n\n" +
		"| Variable | Read by | Expected | Default | Example | Description |\n" +
		"|---|---|---|---|---|---|\n" +
		"| `A_DEV` | Makefile, tests | a port | — | `5` | Dev. |\n"

	en := markdown(testVariables(), false)
	if !strings.HasPrefix(en, prefix) {
		t.Fatalf("english prefix:\n%s", en)
	}

	if !strings.HasSuffix(en, suffix) {
		t.Fatalf("english suffix:\n%s", en)
	}

	pt := markdown(testVariables(), true)
	for _, part := range []string{
		"## Instalação",
		"| Variável | Lida por | Esperado | Padrão | Exemplo | Descrição |",
		"Makefile, testes",
		"Senha.",
	} {
		if !strings.Contains(pt, part) {
			t.Errorf("portuguese output lacks %q", part)
		}
	}

	if strings.Contains(pt, "## Advanced") {
		t.Error("portuguese output holds ## Advanced")
	}
}

func testVariables() []config.Variable {
	return []config.Variable{
		{Name: "A_PASS", Reader: config.Compose, Kind: config.KindPassword, Default: "x", Expected: "letters", Example: "y", Secret: true, Generated: true, Audience: config.Install, Description: "Pass.", DescriptionPT: "Senha."},
		{Name: "A_IP", Reader: config.Compose, Kind: config.KindIP, Default: "127.0.0.1", Expected: "an IP address", Example: "0.0.0.0", Audience: config.Install, Description: "Address.", DescriptionPT: "Endereço."},
		{Name: "A_DEV", Reader: config.Tooling, Kind: config.KindPort, Expected: "a port", Example: "5", Audience: config.Development, Description: "Dev.", DescriptionPT: "Des."},
	}
}
