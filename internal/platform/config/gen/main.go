package main

import (
	"fmt"
	"os"
	"strings"

	"github.com/andrelopes-code/equori/internal/platform/config"
)

const (
	referenceURL = "https://github.com/andrelopes-code/equori/blob/main/docs/install/configuration.md"
	introEN      = "compose.yaml reads the variables of .env in its directory. equori reads its process environment and, in managed mode, equori.env of its data directory (ADR 022, C2). At start, equori checks every variable it reads, prints one line per invalid value and exits with status 1."
	introPT      = "O compose.yaml lê as variáveis do .env do seu diretório. O equori lê o ambiente do processo e, no modo gerenciado, o equori.env do seu diretório de dados (ADR 022, C2). Ao iniciar, o equori verifica cada variável que lê, imprime uma linha por valor inválido e termina com status 1. A coluna Esperado traz o texto das mensagens de início, em inglês."
)

type labels struct {
	header, title, intro                                   string
	install, advanced, development                         string
	variable, readBy, expected, defaultCol, example, descr string
	tooling                                                string
}

var (
	labelsEN = labels{
		header:   "<!-- Generated by make gen from internal/platform/config/variables.go; do not edit. -->",
		title:    "# Configuration",
		intro:    introEN,
		install:  "## Installation",
		advanced: "## Advanced", development: "## Development",
		variable: "Variable", readBy: "Read by", expected: "Expected", defaultCol: "Default",
		example: "Example", descr: "Description", tooling: "Makefile, tests",
	}
	labelsPT = labels{
		header:   "<!-- Gerado por make gen a partir de internal/platform/config/variables.go; não editar. -->",
		title:    "# Configuração",
		intro:    introPT,
		install:  "## Instalação",
		advanced: "## Avançado", development: "## Desenvolvimento",
		variable: "Variável", readBy: "Lida por", expected: "Esperado", defaultCol: "Padrão",
		example: "Exemplo", descr: "Descrição", tooling: "Makefile, testes",
	}
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	vars := config.Variables()
	files := map[string]string{
		"docs/install/configuration.md":       markdown(vars, false),
		"docs/install/configuration.pt-BR.md": markdown(vars, true),
		"env.example":                         envExample(vars),
	}

	if err := os.MkdirAll("docs/install", 0o755); err != nil { //nolint:gosec // repository directories are world-readable
		return err
	}

	for path, content := range files {
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil { //nolint:gosec // repository files are world-readable
			return err
		}
	}

	return nil
}

func markdown(vars []config.Variable, pt bool) string {
	l := labelsEN
	if pt {
		l = labelsPT
	}

	blocks := []string{l.header, l.title, l.intro}

	groups := []struct {
		audience config.Audience
		heading  string
	}{
		{config.Install, l.install},
		{config.Advanced, l.advanced},
		{config.Development, l.development},
	}

	for _, g := range groups {
		if table := table(vars, g.audience, l, pt); table != "" {
			blocks = append(blocks, g.heading, table)
		}
	}

	return strings.Join(blocks, "\n\n") + "\n"
}

func table(vars []config.Variable, audience config.Audience, l labels, pt bool) string {
	var rows []string

	for _, v := range vars {
		if v.Audience != audience {
			continue
		}

		descr := v.Description
		if pt {
			descr = v.DescriptionPT
		}

		def := "—"
		if v.Default != "" {
			def = "`" + v.Default + "`"
		}

		rows = append(rows, fmt.Sprintf("| `%s` | %s | %s | %s | `%s` | %s |",
			v.Name, reader(v.Reader, l), v.Expected, def, v.Example, descr))
	}

	if len(rows) == 0 {
		return ""
	}

	head := []string{
		"| " + strings.Join([]string{l.variable, l.readBy, l.expected, l.defaultCol, l.example, l.descr}, " | ") + " |",
		"|---|---|---|---|---|---|",
	}

	return strings.Join(append(head, rows...), "\n")
}

func reader(r config.Reader, l labels) string {
	switch r {
	case config.Compose:
		return "`compose.yaml`"
	case config.Tooling:
		return l.tooling
	default:
		return "`equori`"
	}
}

func envExample(vars []config.Variable) string {
	var generated []string

	blocks := []string{}

	for _, v := range vars {
		if v.Audience != config.Install {
			continue
		}

		comment := fmt.Sprintf("# %s Expected: %s.", v.Description, v.Expected)
		if v.Default != "" {
			comment += fmt.Sprintf(" Default: %s.", v.Default)
		}

		line := "# " + v.Name + "=" + v.Default
		if v.Generated {
			generated = append(generated, v.Name)
			line = v.Name + "="
		}

		blocks = append(blocks, comment+"\n"+line)
	}

	header := "# equori: variables of compose.yaml, read from .env in this directory.\n" +
		"# Reference: " + referenceURL + "\n" +
		"# The installation script writes " + joinAnd(generated) + "."

	return strings.Join(append([]string{header}, blocks...), "\n\n") + "\n"
}

func joinAnd(names []string) string {
	if len(names) < 2 {
		return strings.Join(names, "")
	}

	return strings.Join(names[:len(names)-1], ", ") + " and " + names[len(names)-1]
}
