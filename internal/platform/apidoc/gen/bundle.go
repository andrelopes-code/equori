package main

import (
	"fmt"
	"strings"
)

const bundleHeader = "# Generated by make gen from api/base.yaml, api/shared.yaml and internal/*/openapi.yaml. Do not edit."

// componentSections are the keys of a fragment that go under components, in output order.
var componentSections = []string{"securitySchemes", "parameters", "responses", "schemas"}

// fragment maps a section name to its lines. A fragment holds the top-level keys paths,
// securitySchemes, parameters, responses and schemas; the children of each sit at two spaces.
type fragment map[string][]string

// bundle joins the base document and the fragments into one OpenAPI document. The base holds the
// top-level keys other than paths and components. Each fragment adds its operations to paths and its
// definitions to the matching components section, in fragment order.
func bundle(base string, fragments []string) (string, error) {
	parsed := make([]fragment, 0, len(fragments))

	for i, text := range fragments {
		f, err := parseFragment(text)
		if err != nil {
			return "", fmt.Errorf("fragment %d: %w", i, err)
		}

		parsed = append(parsed, f)
	}

	out := []string{bundleHeader, strings.TrimRight(base, "\n"), "paths:"}

	for _, f := range parsed {
		out = append(out, f["paths"]...)
	}

	out = append(out, "components:")

	for _, name := range componentSections {
		out = append(out, componentSection(name, parsed)...)
	}

	return strings.Join(out, "\n") + "\n", nil
}

func parseFragment(text string) (fragment, error) {
	f := fragment{}
	current := ""

	for _, line := range strings.Split(strings.TrimRight(text, "\n"), "\n") {
		if name, ok := sectionOf(line); ok {
			current = name

			continue
		}

		if current == "" {
			if strings.TrimSpace(line) == "" {
				continue
			}

			return nil, fmt.Errorf("line %q is outside a section", line)
		}

		f[current] = append(f[current], line)
	}

	return f, nil
}

func sectionOf(line string) (string, bool) {
	name, ok := strings.CutSuffix(line, ":")
	if !ok {
		return "", false
	}

	if name == "paths" {
		return name, true
	}

	for _, known := range componentSections {
		if name == known {
			return name, true
		}
	}

	return "", false
}

// componentSection returns the lines of one components section, indented under components.
func componentSection(name string, fragments []fragment) []string {
	var body []string

	for _, f := range fragments {
		for _, line := range f[name] {
			if strings.TrimSpace(line) != "" {
				line = "  " + line
			}

			body = append(body, line)
		}
	}

	if len(body) == 0 {
		return nil
	}

	return append([]string{"  " + name + ":"}, body...)
}
