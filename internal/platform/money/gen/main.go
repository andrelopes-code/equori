// Command gen writes currency.gen.go from the SIX Group ISO 4217 List One and the exponent lock.
package main

import (
	"bytes"
	"encoding/json"
	"encoding/xml"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strconv"
)

// LockEntry records a currency already shipped. Withdrawn codes stay supported because stored data references them.
type LockEntry struct {
	Exponent int8   `json:"exponent"`
	Name     string `json:"name"`
}

type currencyList struct {
	Entries []struct {
		Name struct {
			Value  string `xml:",chardata"`
			IsFund string `xml:"IsFund,attr"`
		} `xml:"CcyNm"`
		Code  string `xml:"Ccy"`
		Units string `xml:"CcyMnrUnts"`
	} `xml:"CcyTbl>CcyNtry"`
}

// Generate returns the Go source and the updated lock. Funds, entries without a minor unit and entries without a code are excluded.
func Generate(list []byte, lock map[string]LockEntry) ([]byte, map[string]LockEntry, error) {
	var doc currencyList
	if err := xml.Unmarshal(list, &doc); err != nil {
		return nil, nil, fmt.Errorf("parse list one: %w", err)
	}
	out := make(map[string]LockEntry, len(lock))
	for code, e := range lock {
		out[code] = e
	}
	seen := make(map[string]bool)
	for _, e := range doc.Entries {
		if e.Code == "" || e.Name.IsFund == "true" || seen[e.Code] {
			continue
		}
		units, err := strconv.ParseInt(e.Units, 10, 8)
		if err != nil {
			continue
		}
		seen[e.Code] = true
		if prev, ok := lock[e.Code]; ok && prev.Exponent != int8(units) {
			return nil, nil, fmt.Errorf("%s: exponent changed from %d to %d", e.Code, prev.Exponent, units)
		}
		out[e.Code] = LockEntry{Exponent: int8(units), Name: e.Name.Value}
	}
	codes := make([]string, 0, len(out))
	for code := range out {
		codes = append(codes, code)
	}
	slices.Sort(codes)

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/platform/money/gen; DO NOT EDIT.\n\npackage money\n\n")
	b.WriteString("var minorUnits = map[Currency]int8{\n")
	for _, code := range codes {
		fmt.Fprintf(&b, "\t%q: %d,\n", code, out[code].Exponent)
	}
	b.WriteString("}\n\nvar currencyNames = map[Currency]string{\n")
	for _, code := range codes {
		fmt.Fprintf(&b, "\t%q: %q,\n", code, out[code].Name)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("format source: %w", err)
	}
	return src, out, nil
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	list, err := os.ReadFile("internal/platform/money/iso4217.xml")
	if err != nil {
		return err
	}
	raw, err := os.ReadFile("internal/platform/money/iso4217.lock.json")
	if err != nil {
		return err
	}
	var lock map[string]LockEntry
	if err := json.Unmarshal(raw, &lock); err != nil {
		return fmt.Errorf("parse lock: %w", err)
	}
	src, newLock, err := Generate(list, lock)
	if err != nil {
		return err
	}
	enc, err := json.MarshalIndent(newLock, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile("internal/platform/money/currency.gen.go", src, 0o644); err != nil { //nolint:gosec // repository files are world-readable
		return err
	}
	return os.WriteFile("internal/platform/money/iso4217.lock.json", append(enc, '\n'), 0o644) //nolint:gosec // repository files are world-readable
}
