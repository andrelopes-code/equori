// ValidateIcon accepts an empty icon, which means none, or a key of AccountIcons.
func ValidateIcon(icon string) error {
	if icon == "" || slices.Contains(AccountIcons, icon) {
		return nil
	}

	return invalid("icon", "must be a key of the account icon set")
}
